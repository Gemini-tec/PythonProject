# Arithmetic Operators - simple calculations

x = 90
y = 5

# Addition
print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y) # modulus - returns remainder after division

# COMPARISON OPERATORS - Compare values and return boolean
num1 = 45
num2 = 20
print(num1 < num2)
print(num1 > num2)
print(num1 <= num2)
print(num1 >= num2)
print(num1 == num2) #Equal to
print(num1 != num2) # Not Equal to

# ASSIGNMENT OPERATORS- Assign/ store values in a variable
number = 80
print(number)

# operator precedence
number += 2
print(number)

# Logical Operators &&, || , !(More tha one condition to be checked)
print(100 == 50 and 60 < 80)
print(100 == 50 or 60 < 80)
print(not 100 == 50 and 60 < 80)




